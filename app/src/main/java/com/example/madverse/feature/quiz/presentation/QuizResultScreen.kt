/**
 * Screen presenting personalized recommendations generated by the recommendation engine
 * after completing the Movie Preference Quiz.
 */
@Composable
fun QuizResultScreen(
    onMovieClick: (Int) -> Unit,
    onRetakeQuiz: () -> Unit,
    onExploreMore: () -> Unit,
    modifier: Modifier = Modifier,
    viewModel: QuizResultViewModel = hiltViewModel()
) {
    val uiState by viewModel.uiState.collectAsStateWithLifecycle()

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(ObsidianBackground)
    ) {
        when (val state = uiState) {
            is UiState.Loading -> {
                Column(
                    modifier = Modifier.fillMaxSize(),
                    verticalArrangement = Arrangement.Center,
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    CircularProgressIndicator(
                        color = CinematicCrimson,
                        strokeWidth = 3.dp,
                        modifier = Modifier.size(48.dp)
                    )
                    Spacer(modifier = Modifier.height(16.dp))
                    Text(
                        text = "Curating your personalized matches...",
                        style = MaterialTheme.typography.bodyMedium,
                        color = ContentMediumEmphasis
                    )
                }
            }
            is UiState.Error -> {
                MADVerseErrorView(
                    title = "Failed to Load Recommendations",
                    message = state.message,
                    retryLabel = "Try Again",
                    onRetry = { viewModel.loadRecommendations() }
                )
            }
            is UiState.Empty -> {
                MADVerseEmptyState(
                    icon = Icons.Default.Movie,
                    title = "No Matches Found",
                    message = state.message,
                    actionLabel = "Adjust Taste Quiz",
                    onActionClick = onRetakeQuiz
                )
            }
            is UiState.Success -> {
                LazyColumn(
                    modifier = Modifier.fillMaxSize(),
                    contentPadding = PaddingValues(16.dp),
                    verticalArrangement = Arrangement.spacedBy(16.dp)
                ) {
                    item {
                        QuizResultHeader(
                            totalMatches = state.data.size,
                            onRetakeQuiz = onRetakeQuiz
                        )
                    }

                    items(state.data, key = { it.movie.id }) { item ->
                        RecommendedMovieCard(
                            recommendation = item,
                            onClick = { onMovieClick(item.movie.id) }
                        )
                    }

                    item {
                        Spacer(modifier = Modifier.height(8.dp))
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            OutlinedButton(
                                onClick = onRetakeQuiz,
                                modifier = Modifier.weight(1f),
                                shape = RoundedCornerShape(12.dp),
                                border = androidx.compose.foundation.BorderStroke(1.dp, ObsidianCardBorder)
                            ) {
                                Text(
                                    text = "Retake Quiz",
                                    color = ContentHighEmphasis
                                )
                            }
                            Button(
                                onClick = onExploreMore,
                                modifier = Modifier.weight(1f),
                                shape = RoundedCornerShape(12.dp),
                                colors = ButtonDefaults.buttonColors(containerColor = CinematicCrimson)
                            ) {
                                Text(
                                    text = "Discover More",
                                    color = Color.White
                                )
                            }
                        }
                        Spacer(modifier = Modifier.height(16.dp))
                    }
                }
            }
        }
    }
}

@Composable
private fun QuizResultHeader(
    totalMatches: Int,
    onRetakeQuiz: () -> Unit
) {
    Column(
        modifier = Modifier
            .fillMaxWidth()
            .padding(bottom = 8.dp)
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            Icon(
                imageVector = Icons.Default.AutoAwesome,
                contentDescription = null,
                tint = CinematicAmber,
                modifier = Modifier.size(22.dp)
            )
            Text(
                text = "Your Personalized Matches",
                style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold),
                color = ContentHighEmphasis
            )
        }
        Spacer(modifier = Modifier.height(4.dp))
        Text(
            text = "Found $totalMatches films tailored to your favorite genres, era, mood, and ratings.",
            style = MaterialTheme.typography.bodySmall,
            color = ContentMediumEmphasis
        )
    }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun RecommendedMovieCard(
    recommendation: ScoredMovieRecommendation,
    onClick: () -> Unit
) {
    val movie = recommendation.movie

    Box(
        modifier = Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(16.dp))
            .background(ObsidianSurfaceVariant)
            .border(1.dp, ObsidianCardBorder, RoundedCornerShape(16.dp))
            .clickable(onClick = onClick)
            .padding(12.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            // Movie Poster
            Box(
                modifier = Modifier
                    .width(90.dp)
                    .height(135.dp)
                    .clip(RoundedCornerShape(10.dp))
                    .background(Color.Black.copy(alpha = 0.5f))
                    .border(1.dp, ObsidianCardBorder.copy(alpha = 0.5f), RoundedCornerShape(10.dp))
            ) {
                if (movie.posterUrl.isNullOrBlank()) {
                    Box(
                        modifier = Modifier.fillMaxSize(),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.Movie,
                            contentDescription = null,
                            tint = ContentLowEmphasis,
                            modifier = Modifier.size(28.dp)
                        )
                    }
                } else {
                    AsyncImage(
                        model = movie.posterUrl,
                        contentDescription = movie.title,
                        contentScale = ContentScale.Crop,
                        modifier = Modifier.fillMaxSize()
                    )
                }
            }

            // Info & Match details
            Column(
                modifier = Modifier
                    .weight(1f)
                    .padding(vertical = 2.dp)
            ) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    // Match Percentage Badge
                    Box(
                        modifier = Modifier
                            .clip(CircleShape)
                            .background(CinematicAmber.copy(alpha = 0.18f))
                            .border(1.dp, CinematicAmber.copy(alpha = 0.6f), CircleShape)
                            .padding(horizontal = 8.dp, vertical = 2.dp)
                    ) {
                        Text(
                            text = "${recommendation.matchPercentage}% MATCH",
                            style = MaterialTheme.typography.labelSmall.copy(
                                fontWeight = FontWeight.ExtraBold,
                                letterSpacing = 0.6.sp
                            ),
                            color = CinematicAmber
                        )
                    }

                    // Rating
                    MovieRatingBadge(
                        rating = movie.voteAverage,
                        style = RatingBadgeStyle.Inline
                    )
                }

                Spacer(modifier = Modifier.height(6.dp))

                Text(
                    text = movie.title,
                    style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                    color = ContentHighEmphasis,
                    maxLines = 2,
                    overflow = TextOverflow.Ellipsis
                )

                if (!movie.releaseDate.isNullOrBlank()) {
                    val year = movie.releaseDate.take(4)
                    Text(
                        text = year,
                        style = MaterialTheme.typography.bodySmall,
                        color = ContentLowEmphasis
                    )
                }

                Spacer(modifier = Modifier.height(8.dp))

                // Match rationale chips
                if (recommendation.matchReasons.isNotEmpty()) {
                    FlowRow(
                        horizontalArrangement = Arrangement.spacedBy(6.dp),
                        verticalArrangement = Arrangement.spacedBy(4.dp)
                    ) {
                        recommendation.matchReasons.take(3).forEach { reason ->
                            GenreChip(
                                name = reason,
                                textColor = ContentMediumEmphasis,
                                backgroundColor = Color.White.copy(alpha = 0.06f),
                                borderColor = Color.Transparent,
                                cornerRadius = 6.dp
                            )
                        }
                    }
                }
            }

            Icon(
                imageVector = Icons.Default.ChevronRight,
                contentDescription = "View Details",
                tint = ContentLowEmphasis,
                modifier = Modifier
                    .align(Alignment.CenterVertically)
                    .size(20.dp)
            )
        }
    }
}
